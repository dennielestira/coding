def _question(prompt, options, correct_index, explanation):
    options = list(options)
    correct_answer = options.pop(correct_index)
    target_index = sum(map(ord, prompt)) % len(options + [correct_answer])
    options.insert(target_index, correct_answer)
    return {
        "question": prompt,
        "options": options,
        "correct_index": target_index,
        "explanation": explanation,
    }


